from __future__ import annotations

import json
import logging
from pathlib import Path

from fastapi import APIRouter, Query
from sqlalchemy import func, select

from backend.database.connection import session_scope
from backend.database.models import PredictionLog
from backend.ml.feature_config import PROTECTED_ATTRIBUTES, TARGET_COLUMN, TARGET_RAW_COLUMN, ACTION_TO_LABEL

logger = logging.getLogger(__name__)
router = APIRouter(tags=["dataset"])

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
DATA_SUMMARY_PATH = PROJECT_ROOT / "data" / "reports" / "data_summary.json"


@router.get("/dataset/info")
def dataset_info() -> dict:
    """
    Read-only summary of the dataset the active model was trained on:
    where the target came from, which rows were kept/excluded and why,
    and which protected attributes exist for the fairness evaluation.
    Numbers come from data/reports/data_summary.json, generated by
    scripts/prepare_data.py — nothing here is hand-typed.
    """
    info: dict = {
        "dataset_name": "Washington State HMDA 2016",
        "target_column": TARGET_COLUMN,
        "target_source_column": TARGET_RAW_COLUMN,
        "target_derivation": {
            raw_value: ("denied" if label == 1 else "not_denied")
            for raw_value, label in ACTION_TO_LABEL.items()
        },
        "protected_attributes": {
            name: {"column": cfg["column"], "privileged": cfg["privileged"], "comparison": cfg["comparison"]}
            for name, cfg in PROTECTED_ATTRIBUTES.items()
        },
    }

    if DATA_SUMMARY_PATH.exists():
        with open(DATA_SUMMARY_PATH) as f:
            summary = json.load(f)
        info["ready"] = True
        info["raw_row_count"] = summary.get("raw_row_count")
        info["rows_after_target_filter"] = summary.get("rows_after_target_filter")
        info["rows_excluded_ambiguous_action"] = summary.get("rows_excluded_ambiguous_action")
        info["target_class_balance"] = summary.get("target_class_balance")
        info["split_sizes"] = summary.get("split_sizes")
        info["split_strategy"] = summary.get("split_strategy")
    else:
        info["ready"] = False
        info["error"] = "No data summary found. Run scripts/prepare_data.py."

    return info


@router.get("/predictions")
def list_predictions(limit: int = Query(default=20, ge=1, le=200), offset: int = Query(default=0, ge=0)) -> dict:
    """
    Prediction history actually stored in MySQL by /predict and
    /predict/batch. Returns an empty list (not an error) if the database
    is unreachable or the table is empty -- this is an audit view, not a
    critical-path feature, so it degrades gracefully.
    """
    try:
        with session_scope() as db:
            total = db.execute(select(func.count()).select_from(PredictionLog)).scalar_one()
            rows = (
                db.execute(
                    select(PredictionLog).order_by(PredictionLog.id.desc()).limit(limit).offset(offset)
                )
                .scalars()
                .all()
            )
            return {
                "ready": True,
                "total": total,
                "count": len(rows),
                "limit": limit,
                "offset": offset,
                "predictions": [
                    {
                        "id": r.id,
                        "created_at": r.created_at.isoformat(),
                        "model_version": r.model_version,
                        "loan_amount_000s": r.loan_amount_000s,
                        "applicant_income_000s": r.applicant_income_000s,
                        "loan_type_name": r.loan_type_name,
                        "loan_purpose_name": r.loan_purpose_name,
                        "predicted_label": r.predicted_label,
                        "denial_probability": r.denial_probability,
                    }
                    for r in rows
                ],
            }
    except Exception as exc:  # noqa: BLE001
        logger.warning("Could not read prediction history: %s", exc)
        return {"ready": False, "total": 0, "count": 0, "predictions": [], "error": str(exc)}


@router.get("/predictions/stats")
def prediction_stats() -> dict:
    """
    Aggregate counts over every prediction ever logged, computed with
    real SQL COUNT/AVG queries against MySQL -- backs the Dashboard page.
    Degrades to ready=False (not an error) if the database or table
    isn't available yet.
    """
    try:
        with session_scope() as db:
            total = db.execute(select(func.count()).select_from(PredictionLog)).scalar_one()
            if total == 0:
                return {"ready": True, "total": 0, "denied": 0, "not_denied": 0, "denial_rate": None, "approval_rate": None}
            denied = db.execute(
                select(func.count()).select_from(PredictionLog).where(PredictionLog.predicted_label == "denied")
            ).scalar_one()
            not_denied = total - denied
            avg_prob = db.execute(select(func.avg(PredictionLog.denial_probability))).scalar_one()
            return {
                "ready": True,
                "total": total,
                "denied": denied,
                "not_denied": not_denied,
                "denial_rate": round(denied / total, 4),
                "approval_rate": round(not_denied / total, 4),
                "average_denial_probability": round(float(avg_prob), 4) if avg_prob is not None else None,
            }
    except Exception as exc:  # noqa: BLE001
        logger.warning("Could not compute prediction stats: %s", exc)
        return {"ready": False, "error": str(exc)}
